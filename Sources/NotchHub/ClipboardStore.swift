import AppKit
import Combine

struct ClipItem: Identifiable, Codable, Equatable {
    enum Kind: String, Codable { case text, image, files }

    var id = UUID()
    var kind: Kind
    var text: String?
    var imageFile: String?   // имя PNG в папке хранилища
    var fileURLs: [URL]?
    var date = Date()
    var sourceApp: String?
}

/// Следит за системным буфером обмена и хранит историю (до `limit` записей) на диске.
final class ClipboardStore: ObservableObject {
    @Published private(set) var items: [ClipItem] = []

    private let limit = 60
    private let pasteboard = NSPasteboard.general
    private var lastChangeCount: Int
    private var timer: Timer?
    private var imageCache: [String: NSImage] = [:]

    private let storageDir: URL = {
        let dir = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
            .appendingPathComponent("NotchHub", isDirectory: true)
        try? FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        return dir
    }()
    private var historyFile: URL { storageDir.appendingPathComponent("clipboard.json") }

    // Менеджеры паролей помечают секреты этими типами — их не сохраняем.
    private let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    init() {
        lastChangeCount = pasteboard.changeCount
        load()
    }

    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            self?.poll()
        }
        RunLoop.main.add(timer!, forMode: .common)
    }

    // MARK: - Чтение буфера

    private func poll() {
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount

        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: ignoredTypes) else { return }

        let app = NSWorkspace.shared.frontmostApplication?.localizedName

        if types.contains(NSPasteboard.PasteboardType.fileURL.rawValue),
           let urls = pasteboard.readObjects(forClasses: [NSURL.self],
                                             options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            insert(ClipItem(kind: .files, fileURLs: urls, sourceApp: app))
        } else if let string = pasteboard.string(forType: .string),
                  !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            insert(ClipItem(kind: .text, text: string, sourceApp: app))
        } else if let image = NSImage(pasteboard: pasteboard),
                  let name = saveImage(image) {
            insert(ClipItem(kind: .image, imageFile: name, sourceApp: app))
        }
    }

    private func insert(_ item: ClipItem) {
        // Повтор уже существующего содержимого — просто поднимаем наверх.
        if let index = items.firstIndex(where: { $0.isSameContent(as: item) }) {
            var existing = items.remove(at: index)
            existing.date = Date()
            items.insert(existing, at: 0)
        } else {
            items.insert(item, at: 0)
        }
        while items.count > limit {
            removeFiles(of: items.removeLast())
        }
        save()
    }

    // MARK: - Действия

    /// Кладёт запись обратно в системный буфер.
    func copy(_ item: ClipItem) {
        pasteboard.clearContents()
        switch item.kind {
        case .text:
            pasteboard.setString(item.text ?? "", forType: .string)
        case .image:
            if let image = image(for: item) { pasteboard.writeObjects([image]) }
        case .files:
            pasteboard.writeObjects((item.fileURLs ?? []) as [NSURL])
        }
        lastChangeCount = pasteboard.changeCount
        insert(item)
    }

    func delete(_ item: ClipItem) {
        items.removeAll { $0.id == item.id }
        removeFiles(of: item)
        save()
    }

    func clear() {
        items.forEach(removeFiles)
        items.removeAll()
        save()
    }

    func image(for item: ClipItem) -> NSImage? {
        guard let name = item.imageFile else { return nil }
        if let cached = imageCache[name] { return cached }
        let image = NSImage(contentsOf: storageDir.appendingPathComponent(name))
        imageCache[name] = image
        return image
    }

    // MARK: - Хранилище

    private func saveImage(_ image: NSImage) -> String? {
        guard let tiff = image.tiffRepresentation,
              let rep = NSBitmapImageRep(data: tiff),
              let png = rep.representation(using: .png, properties: [:]) else { return nil }
        let name = UUID().uuidString + ".png"
        do {
            try png.write(to: storageDir.appendingPathComponent(name))
            imageCache[name] = image
            return name
        } catch {
            return nil
        }
    }

    private func removeFiles(of item: ClipItem) {
        guard let name = item.imageFile else { return }
        // Тот же PNG мог остаться у другой записи (после повторного копирования) — проверяем.
        guard !items.contains(where: { $0.imageFile == name }) else { return }
        imageCache[name] = nil
        try? FileManager.default.removeItem(at: storageDir.appendingPathComponent(name))
    }

    private func load() {
        guard let data = try? Data(contentsOf: historyFile),
              let decoded = try? JSONDecoder().decode([ClipItem].self, from: data) else { return }
        items = decoded
    }

    private func save() {
        guard let data = try? JSONEncoder().encode(items) else { return }
        try? data.write(to: historyFile, options: .atomic)
    }
}

extension ClipItem {
    func isSameContent(as other: ClipItem) -> Bool {
        guard kind == other.kind else { return false }
        switch kind {
        case .text: return text == other.text
        case .files: return fileURLs == other.fileURLs
        case .image: return imageFile == other.imageFile
        }
    }
}

extension ClipboardStore {
    /// Подменяет историю демо-данными (только для `--snapshot --demo`, на диск не сохраняется).
    func loadDemo(_ demo: [ClipItem], images: [String: NSImage]) {
        imageCache.merge(images) { $1 }
        items = demo
    }
}
